const {chromium} = require('playwright'); const path = require('path');
const out = path.join(__dirname, 'shots12'); require('fs').mkdirSync(out, {recursive: true});
(async () => { const b = await chromium.launch(); const p = await b.newPage({viewport: {width: 702, height: 936}});
  p.on('pageerror', e => console.log('PAGE ERROR:', e.message));
  p.on('console', m => m.text().startsWith('LOG') && /epub|wish|reading|dup/i.test(m.text()) && console.log(m.text()));
  const L = s => p.getByLabel(s, {exact: true}).first();
  const tab = name => p.getByRole('button', {name, exact: true}).last();
  const shot = async n => { await p.waitForTimeout(400); await p.screenshot({path: path.join(out, n + '.png')}); console.log('shot', n); };
  await p.goto('file://' + path.join(__dirname, 'index.html') + '?lib=2&state=1&reading=1'); await p.waitForTimeout(2500);
  await shot('00-home-reading-now');
  await p.waitForTimeout(4000);
  await tab('Profile').click(); await shot('01-profile');
  await L('Notes and quotes').click(); await shot('02-quotes');
  await p.getByPlaceholder('Search your notes and quotes').fill('line'); await shot('03-quotes-search');
  await L('Profile').click(); await L('Wishlist').click(); await shot('04-wishlist');
  await L('Add a book to the wishlist').click(); await p.getByPlaceholder('The book you want').fill('The Glass Orchard'); await p.getByPlaceholder('Optional', {exact: true}).fill('Ren Hao'); await shot('05-wishlist-add');
  await p.getByLabel('Cancel', {exact: true}).last().click();
  await tab('Collections').click(); await shot('06-collections-wishlist-tile');
  await tab('Library').click(); await p.waitForTimeout(800); await shot('07-library-authors'); console.log('MINSEO', await p.evaluate(() => { const t = document.body.innerText; const i = t.indexOf('The Lighthouse Keeper'); return t.slice(i, i + 60); }));
  await tab('Home').click(); await p.getByText('Rain Over Busan').first().click(); await p.waitForTimeout(500); await shot('08-book-dup-continue');
  await p.getByLabel(/^2 notes/).first().click(); await p.waitForTimeout(400); await shot('09-notes-board-stars');
  await p.getByLabel(/^Note 2:/).first().click(); await shot('10-note-editor-top');
  await p.getByLabel('Cancel', {exact: true}).last().click(); await L('Back to the book').click(); await L('Close').click().catch(() => {});
  await p.goto('file://' + path.join(__dirname, 'index.html') + '?lib=2&state=1'); await p.waitForTimeout(3000);
  await L('Settings').click(); await shot('11-settings-dash');
  await p.goto('file://' + path.join(__dirname, 'index.html') + '?lib=2&state=1&reading=1'); await p.waitForTimeout(1500); await shot('12-reading-now-toast'); await p.waitForTimeout(4200); await shot('13-then-wishlist-toast');
  await b.close(); })();
