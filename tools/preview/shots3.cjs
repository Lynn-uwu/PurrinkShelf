const {chromium} = require('playwright');
const path = require('path');
const dir = __dirname, out = path.join(dir, 'shots3');
require('fs').mkdirSync(out, {recursive: true});
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({viewport: {width: 702, height: 936}});
  p.on('pageerror', e => console.log('PAGE ERROR:', e.message));
  const shot = async n => { await p.waitForTimeout(400); await p.screenshot({path: path.join(out, n + '.png')}); console.log('shot', n); };
  const url = q => 'file://' + path.join(dir, 'index.html') + q;
  const tab = name => p.getByRole('button', {name, exact: true}).last();
  const L = s => p.getByLabel(s, {exact: true}).first();
  await p.goto(url('?lib=2&state=1')); await p.waitForTimeout(900);
  await tab('Library').click(); await p.waitForTimeout(6000); await shot('01-library-filters');
  await L('Tags').click(); await shot('02-tags');
  await L('More filters').click(); await shot('03-more');
  await p.getByText('Not read yet').click(); await p.getByText('Bookmarked').click(); await p.getByText('Bookmarked').click(); await shot('04-more-on');
  await L('Genre').click(); await shot('05-genre-dot');
  await p.getByText('Clear', {exact: true}).click();
  await L('Choose a category').click(); await shot('06-category-sheet');
  await L('Historical').click(); await shot('07-category-historical');
  await L('Choose a category').click(); await L('All').click();
  await L('Sort').click(); await shot('08-sort-sheet');
  await L('Close').click();
  await L('Hide filters').click(); await L('Grid view').click(); await shot('09-grid-no-panel');
  await L('Show filters').click(); await shot('10-grid-panel');
  await L('Data and storage').click(); await shot('11-data-backup');
  await p.getByText('Back up now').click(); await shot('12-backed-up');
  await p.getByText('Change folder').click(); await shot('13-backup-folder');
  await b.close();
  const b2 = await chromium.launch(); const q = await b2.newPage({viewport: {width: 702, height: 936}});
  q.on('pageerror', e => console.log('PAGE ERROR:', e.message));
  await q.goto(url('?backup=1')); await q.waitForTimeout(1200); await q.screenshot({path: path.join(out, '14-restored-home.png')}); console.log('shot 14');
  await q.getByRole('button', {name: 'Library', exact: true}).last().click(); await q.waitForTimeout(1500); await q.screenshot({path: path.join(out, '15-restored-library.png')}); console.log('shot 15');
  await b2.close();
})();
