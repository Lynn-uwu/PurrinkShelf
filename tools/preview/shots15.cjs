const {chromium} = require('playwright'); const path = require('path');
const out = path.join(__dirname, 'shots15'); require('fs').mkdirSync(out, {recursive: true});
(async () => { const b = await chromium.launch(); const p = await b.newPage({viewport: {width: 702, height: 936}});
  p.on('pageerror', e => console.log('PAGE ERROR:', e.message));
  const L = s => p.getByLabel(s, {exact: true}).first();
  const tab = name => p.getByRole('button', {name, exact: true}).last();
  const outside = () => p.mouse.click(350, 12);
  const has = async t => (await p.getByText(t, {exact: true}).count()) > 0;
  const shot = async n => { await p.waitForTimeout(350); await p.screenshot({path: path.join(out, n + '.png')}); };
  await p.goto('file://' + path.join(__dirname, 'index.html') + '?lib=2&state=1'); await p.waitForTimeout(7000);
  await tab('Profile').click(); await L('Settings').click();
  await p.getByText('Data and storage').first().click(); await p.waitForTimeout(300); await shot('1-data');
  await outside(); await shot('2-after-outside'); console.log('data -> settings:', await has('Show on Profile'));
  await p.getByText('Activity', {exact: true}).first().click(); await p.waitForTimeout(300);
  await outside(); console.log('activity -> settings:', await has('Show on Profile'));
  await p.getByText('How to use', {exact: true}).first().click(); await p.waitForTimeout(300);
  await L('Back').click(); await p.waitForTimeout(300); console.log('help -> settings:', await has('Show on Profile'));
  await outside(); await p.waitForTimeout(300); console.log('settings -> profile:', !(await has('Show on Profile')) && await has('Reading days'));
  await tab('Home').click(); await p.getByText('Rain Over Busan').first().click(); await p.waitForTimeout(400);
  await L('Edit details').click(); await p.waitForTimeout(300); await outside(); await p.waitForTimeout(300);
  console.log('edit -> book:', await has('Description'));
  await outside(); await p.waitForTimeout(300); console.log('book -> home:', await has('Recent searches'));
  await b.close(); })();
