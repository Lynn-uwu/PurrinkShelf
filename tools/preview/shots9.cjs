const {chromium} = require('playwright'); const path = require('path');
const out = path.join(__dirname, 'shots9'); require('fs').mkdirSync(out, {recursive: true});
(async () => { const b = await chromium.launch(); const p = await b.newPage({viewport: {width: 702, height: 936}});
  p.on('pageerror', e => console.log('PAGE ERROR:', e.message));
  const L = s => p.getByLabel(s, {exact: true}).first();
  const tab = name => p.getByRole('button', {name, exact: true}).last();
  const shot = async n => { await p.waitForTimeout(400); await p.screenshot({path: path.join(out, n + '.png')}); console.log('shot', n); };
  await p.goto('file://' + path.join(__dirname, 'index.html') + '?lib=2&state=1'); await p.waitForTimeout(1500);
  await shot('01-home-taskbar');
  await tab('Collections').click(); await p.waitForTimeout(1500); await shot('02-collections-grid');
  await L('Open Bookmarks').click(); await shot('03-bookmarks');
  await L('Edit Bookmarks').click(); await shot('04-edit-mode');
  await L('Done editing').click();
  await L('Choose a collection').click(); await shot('05-collection-dropdown');
  await L('Close collections list').click();
  await L('All collections').click();
  await L('New collection').click(); await p.getByPlaceholder('e.g. Cosy reads, To reread, Book club').fill('Finished romances');
  await p.getByText('Add a rule').click(); await p.getByText('Add a rule').click();
  await L('Rule field').click(); await shot('06-rule-field-dropdown');
  await p.getByText('Reading status', {exact: true}).last().click();
  await L('Rule value').click(); await shot('07-rule-value-dropdown');
  await p.getByText('Completed', {exact: true}).last().click();
  await p.getByLabel('Rule value', {exact: true}).nth(1).click(); await shot('08-genre-dropdown');
  await p.getByText('Romance', {exact: true}).last().click(); await shot('09-rules-done');
  await p.getByText('Save collection').click(); await p.waitForTimeout(300); await shot('10-saved');
  await tab('Library').click(); await p.waitForTimeout(800);
  await L('Choose a category').click(); await shot('11-category-dropdown');
  await b.close(); })();
