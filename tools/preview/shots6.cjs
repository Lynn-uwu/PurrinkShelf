const {chromium} = require('playwright');
const path = require('path');
const dir = __dirname, out = path.join(dir, 'shots6');
require('fs').mkdirSync(out, {recursive: true});
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({viewport: {width: 702, height: 936}});
  p.on('pageerror', e => console.log('PAGE ERROR:', e.message));
  const shot = async n => { await p.waitForTimeout(400); await p.screenshot({path: path.join(out, n + '.png')}); console.log('shot', n); };
  const url = q => 'file://' + path.join(dir, 'index.html') + q;
  const L = s => p.getByLabel(s, {exact: true}).first();
  const tab = name => p.getByRole('button', {name, exact: true}).last();
  await p.goto(url('?lib=2&state=1')); await p.waitForTimeout(900);
  await tab('Library').click(); await p.waitForTimeout(6000);
  await p.getByText('Echoes of the Ninth Gate').first().click(); await p.waitForTimeout(400);
  await L('Next').click().catch(() => {}); await shot('01-volume-names');
  await L("Check this book's files again").click(); await p.waitForTimeout(700); await shot('02-reload');
  await p.mouse.click(8, 450); await p.waitForTimeout(300);
  await p.getByText('JavaScript Fundamentals').first().click(); await p.waitForTimeout(400); await shot('03-chapters');
  await p.mouse.click(8, 450); await p.waitForTimeout(300);
  await tab('Collections').click(); await p.getByText('Moon Over the Jade Pavilion').first().click(); await p.waitForTimeout(400);
  await L('3 notes').click(); await shot('04-notes-board');
  await L('Choose notes to delete').click(); await L('Select note 1').click(); await L('Select note 3').click(); await shot('05-delete-select');
  await L('Cancel deleting').click();
  await p.getByLabel(/^Note 2:/).click(); await shot('06-note-open');
  await L('Cancel').click(); await L('Close notes').click();
  await p.mouse.click(8, 450); await p.waitForTimeout(300);
  await tab('Settings').click(); await shot('07-settings-card');
  await p.mouse.click(8, 450); await p.waitForTimeout(300);
  await tab('Library').click(); await L('Choose a category').click(); await shot('08-category-2col');
  await L('Close').click();
  await L('Data and storage').click(); await p.waitForTimeout(300); await shot('09-data-sheet');
  await L('How to fill in the sheet').click(); await shot('10-sheet-help');
  console.log((await p.evaluate(() => Object.keys(window.__files || {}).filter(k => k.endsWith('.csv')))));
  await b.close();
})();
