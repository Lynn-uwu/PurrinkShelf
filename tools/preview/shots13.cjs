const {chromium} = require('playwright'); const path = require('path');
const out = path.join(__dirname, 'shots13'); require('fs').mkdirSync(out, {recursive: true});
(async () => { const b = await chromium.launch(); const p = await b.newPage({viewport: {width: 702, height: 936}});
  p.on('pageerror', e => console.log('PAGE ERROR:', e.message));
  p.on('console', m => m.text().startsWith('LOG') && /details|site|paper|scan/i.test(m.text()) && console.log(m.text()));
  const L = s => p.getByLabel(s, {exact: true}).first();
  const tab = name => p.getByRole('button', {name, exact: true}).last();
  const shot = async n => { await p.waitForTimeout(400); await p.screenshot({path: path.join(out, n + '.png')}); console.log('shot', n); };
  const U = q => 'file://' + path.join(__dirname, 'index.html') + q;
  await p.goto(U('?lib=2&state=1&goal=1')); await p.waitForTimeout(1500); await shot('01-message-see-through');
  await p.waitForTimeout(5000);
  await tab('Profile').click(); await shot('02-profile-goal-time');
  await L('Settings').click(); await shot('03-settings-extras');
  await p.getByText('Activity', {exact: true}).first().click(); await shot('04-activity');
  await L('Close page').click();
  await tab('Library').click(); await p.waitForTimeout(800);
  await L('Add a paper book').click(); await p.getByPlaceholder('The book on your shelf').fill('Norwegian Wood'); await p.getByPlaceholder('Optional', {exact: true}).fill('Haruki Murakami'); await shot('05-add-paper');
  await p.getByLabel('Cancel', {exact: true}).last().click();
  await p.getByText('All', {exact: true}).first().click(); await p.waitForTimeout(300); await p.getByText('Paper books', {exact: true}).last().click(); await p.waitForTimeout(500); await shot('06-paper-category');
  await p.getByText('The Little Prince').first().click(); await p.waitForTimeout(500); await shot('07-paper-book');
  await L('Next page').last().click().catch(() => {}); await p.waitForTimeout(300);
  await p.getByLabel('Next', {exact: false}).first().click().catch(() => {});
  await shot('08-paper-details');
  await b.close(); })();
