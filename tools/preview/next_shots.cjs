const {chromium} = require('playwright'); const path = require('path');
const out = path.join(__dirname, 'shots28'); require('fs').mkdirSync(out, {recursive: true});
(async () => { const b = await chromium.launch(); const p = await b.newPage({viewport: {width: 702, height: 936}});
  p.on('pageerror', e => console.log('PAGE ERROR:', e.message));
  const shot = async n => { await p.waitForTimeout(700); await p.screenshot({path: path.join(out, n + '.png')}); console.log(n); };
  await p.goto('file://' + path.join(__dirname, 'index.html') + '?lib=1&state=1&prog=1&reading=echo&page=410&pages=412'); await p.waitForTimeout(14000);
  await shot('7-next');
  await p.getByText('Later', {exact: true}).click(); await shot('8-later');
  await p.getByLabel('Chapters', {exact: true}).click(); await shot('9-chapters-end');
  await b.close(); })();
