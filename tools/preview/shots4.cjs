const {chromium} = require('playwright');
const path = require('path');
const dir = __dirname, out = path.join(dir, 'shots4');
require('fs').mkdirSync(out, {recursive: true});
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({viewport: {width: 702, height: 936}});
  p.on('pageerror', e => console.log('PAGE ERROR:', e.message));
  const shot = async n => { await p.waitForTimeout(400); await p.screenshot({path: path.join(out, n + '.png')}); console.log('shot', n); };
  const url = q => 'file://' + path.join(dir, 'index.html') + q;
  const tab = name => p.getByRole('button', {name, exact: true}).last();
  const L = s => p.getByLabel(s, {exact: true}).first();
  await p.goto(url('?lib=2&state=1')); await p.waitForTimeout(900);
  await tab('Library').click(); await p.waitForTimeout(6000);
  await L('Next page').click(); await p.getByText('Moon Over the Jade Pavilion').first().click(); await shot('01-book-card');
  await L('Reading status').click(); await shot('02-status-sheet');
  await L('Completed').click(); await shot('03-completed');
  await L('Favourite').click(); await p.getByLabel('Collections', {exact: true}).last().click(); await shot('04-collections-sheet');
  await L('Close').click();
  await L('Edit details').click(); await shot('05-edit-card');
  await p.getByPlaceholder('e.g. 94 Chapters + 6 Extras (Completed)').fill('112 Chapters + 6 Extras (Completed)');
  await L('Close page').click(); await shot('06-save-or-discard');
  await p.getByText('Discard changes').click(); await shot('07-back-on-book');
  await L('Close page').click(); await shot('08-closed-to-library');
  await tab('Collections').click(); await shot('09-collections-bookmarks');
  await p.getByText(/^Favourites/).first().click(); await shot('10-favourites');
  await p.getByText(/^Completed/).first().click(); await shot('11-completed');
  await L('New collection').click(); await shot('12-new-collection');
  await p.getByPlaceholder('e.g. Cosy reads, To reread, Book club').fill('Cosy romance');
  await p.getByText('Add a rule').click(); await L('Rule value').click(); await shot('13-pick-value');
  await p.getByText('Romance', {exact: true}).last().click();
  await p.getByText('Add a rule').click(); await L('Rule field').nth(0); 
  await p.getByLabel('Rule field', {exact: true}).nth(1).click(); await p.getByText('Tag', {exact: true}).last().click();
  await p.getByLabel('Include or exclude', {exact: true}).nth(1).click();
  await p.getByLabel('Rule value', {exact: true}).nth(1).click(); await p.getByText('Court Politics', {exact: true}).last().click(); await shot('14-rules');
  await p.getByText('Save collection').click(); await shot('15-cosy');
  await L('Data and storage').click().catch(async () => { await tab('Home').click(); await L('Data and storage').click(); });
  await p.waitForTimeout(300); await shot('16-data-eye');
  await L('Leave folders out of Novels').click(); await shot('17-exclude');
  await L('Leave out _Library Data').click(); await L('Open Chinese Novels').click(); await L('Leave out Historical').click(); await shot('18-exclude-chinese');
  await L('Up one folder').click(); await shot('19-exclude-root');
  await b.close();
})();
